/**
 * Crisp stroke icon set (feather-style) used across the app.
 * All icons inherit `currentColor` and scale via the `size` prop.
 */
function Icon({ size = 20, children, strokeWidth = 2, ...props }: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  );
}

